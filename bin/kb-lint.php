<?php

/**
 * bin/kb-lint.php — validate the .workflow/helpers/ knowledge base.
 *
 * Checks every ### entry in faq.md / decisions.md carries single-line front
 * matter in an HTML comment right after its heading, with fields: id, date,
 * tags, trigger, status (hits optional). Regenerates the tag index at the top
 * of each file with --fix. Warns above 300 lines per file and lists stale
 * entries.
 *
 * Usage:
 *   php bin/kb-lint.php          # check only
 *   php bin/kb-lint.php --fix    # rewrite tag indexes
 *
 * Exit codes: 0 ok, 1 lint errors, 2 no helpers dir.
 */
declare(strict_types=1);

$fix = in_array('--fix', $_SERVER['argv'] ?? [], true);
$dir = __DIR__ . '/../.workflow/helpers';

if (!is_dir($dir)) {
    fwrite(STDERR, "No .workflow/helpers/ directory — nothing to lint.\n");
    exit(2);
}

$files = ['faq.md', 'decisions.md'];
$errors = 0;
$warnings = 0;

/** Parse entries (heading + front matter comment + tags). */
function parseEntries(string $content): array
{
    $entries = [];
    $lines = preg_split('/\r\n|\r|\n/', $content);
    $count = count($lines);
    for ($i = 0; $i < $count; $i++) {
        $line = $lines[$i];
        if (preg_match('/^###\s+(.+)$/', $line, $m)) {
            $entry = ['title' => trim($m[1]), 'line' => $i + 1, 'fm' => [], 'tags' => [], 'id' => null, 'status' => null];
            // Next non-empty line should be an HTML comment with front matter.
            for ($j = $i + 1; $j < $count; $j++) {
                $next = trim($lines[$j]);
                if ($next === '') {
                    continue;
                }
                if (preg_match('/^<!--\s*(.+?)\s*-->$/', $next, $fm)) {
                    $fields = [];
                    foreach (explode(',', $fm[1]) as $pair) {
                        [$k, $v] = array_pad(array_map(trim(...), explode('=', $pair, 2)), 2, '');
                        $fields[$k] = $v;
                    }
                    $entry['fm'] = $fields;
                    $entry['id'] = $fields['id'] ?? null;
                    $entry['status'] = $fields['status'] ?? null;
                    $entry['tags'] = array_values(array_filter(array_map(trim(...), explode(' ', $fields['tags'] ?? ''))));
                }
                break;
            }
            $entries[] = $entry;
        }
    }
    return $entries;
}

/** Build a tag index block. */
function buildIndex(array $entries): string
{
    $byTag = [];
    foreach ($entries as $e) {
        foreach ($e['tags'] as $t) {
            if ($e['id'] === null) {
                continue;
            }
            $byTag[$t][] = $e['id'];
        }
    }
    ksort($byTag);
    $lines = ['<!-- TAG INDEX (generated by bin/kb-lint.php — do not edit by hand) -->'];
    foreach ($byTag as $tag => $ids) {
        $ids = array_values(array_unique($ids));
        sort($ids);
        $lines[] = "- `{$tag}`: " . implode(', ', $ids);
    }
    $lines[] = '<!-- /TAG INDEX -->';
    return implode("\n", $lines);
}

foreach ($files as $name) {
    $path = $dir . '/' . $name;
    if (!file_exists($path)) {
        continue;
    }
    $content = file_get_contents($path);
    $lineCount = substr_count($content, "\n") + 1;
    if ($lineCount > 300) {
        echo "WARN: {$name} is {$lineCount} lines (>300) — consider splitting.\n";
        $warnings++;
    }

    $entries = parseEntries($content);
    $ids = [];
    foreach ($entries as $e) {
        if ($e['id'] === null) {
            echo "ERROR: {$name}:{$e['line']} missing front matter id ({$e['title']})\n";
            $errors++;
            continue;
        }
        if (in_array($e['id'], $ids, true)) {
            echo "ERROR: {$name}:{$e['line']} duplicate id '{$e['id']}'\n";
            $errors++;
        }
        $ids[] = $e['id'];
        foreach (['id', 'date', 'tags', 'trigger', 'status'] as $field) {
            if (!isset($e['fm'][$field]) || $e['fm'][$field] === '') {
                echo "ERROR: {$name}:{$e['line']} missing field '{$field}' in id '{$e['id']}'\n";
                $errors++;
            }
        }
        if ($e['status'] === 'stale') {
            echo "WARN: {$name}:{$e['line']} entry '{$e['id']}' is stale\n";
            $warnings++;
        }
    }

    if ($fix) {
        // Replace existing index block or insert after the first heading.
        $newIndex = buildIndex($entries);
        $pattern = '/<!-- TAG INDEX .*?<!-- \/TAG INDEX -->/s';
        if (preg_match($pattern, $content)) {
            $content = preg_replace($pattern, $newIndex, $content, 1);
        } else {
            // Insert before the first ### entry, after the intro.
            $content = preg_replace('/(\n)(### )/s', "\n" . $newIndex . "\n\n$2", $content, 1);
        }
        file_put_contents($path, $content);
        echo "Fixed: rewrote tag index in {$name}\n";
    }
}

if ($errors > 0) {
    fwrite(STDERR, "\nkb-lint: {$errors} error(s), {$warnings} warning(s)\n");
    exit(1);
}
echo "kb-lint: ok ({$warnings} warning(s))\n";
exit(0);
